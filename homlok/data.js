function makeActors(names, origin) {
  return names.map((name) => ({
    id: `${origin}-${name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`,
    name,
    origin,
    type: 'actor',
  }));
}

export const ACTORS = [
  ...makeActors(worldNames, 'world'),
  ...makeActors(hungarianNames, 'hungarian'),
];

export const MOVIES = movieNames.map((name) => ({
  id: `movie-${name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`,
  name,
  type: 'movie',
}));

export function getDeckCards(deckId) {
  if (deckId === 'mix') return [...ACTORS, ...MOVIES];
  if (deckId === 'movies') return [...MOVIES];
  if (deckId === 'world' || deckId === 'hungarian') {
    return ACTORS.filter((actor) => actor.origin === deckId);
  }
  return [];
}
